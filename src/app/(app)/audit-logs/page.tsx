import { redirect } from "next/navigation";
import Link from "next/link";
import { Activity, Clock3, ScrollText, ShieldCheck, Users } from "lucide-react";
import { getSessionUser } from "@/server/session";
import { buildScope } from "@/server/access";
import { listAuditLogs } from "@/server/audit";
import { can } from "@/lib/rbac";
import { formatDateTime, formatNumber, formatRelative } from "@/lib/utils";
import { PageHeader } from "@/components/ui/page-header";
import { StatCard } from "@/components/ui/stat-card";
import { Card, CardHeader } from "@/components/ui/card";
import { PermissionDenied } from "@/components/ui/states";
import { AuditFilters } from "./audit-filters";
import { AuditTable } from "./audit-table";

export const metadata = { title: "Audit Logs" };

export default async function AuditLogsPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const user = await getSessionUser();
  if (!user) redirect("/login");
  if (!can(user, "audit:view")) {
    return <PermissionDenied className="mt-2" />;
  }

  const params = await searchParams;
  const value = (key: string) => (typeof params[key] === "string" ? (params[key] as string) : undefined);

  const scope = buildScope(user);
  const directory = listAuditLogs(scope, {
    q: value("q"),
    action: value("action"),
    actorId: value("actor"),
    from: value("from"),
    to: value("to"),
  });

  const activeFilterCount = [value("q"), value("action"), value("actor"), value("from"), value("to")].filter(
    Boolean,
  ).length;

  return (
    <div className="space-y-5">
      <PageHeader
        eyebrow="Administration"
        title="Audit logs"
        description={`Chronological, append-only activity trail for ${
          scope.isGlobal ? "all branches" : user.branchName
        }. Records are scoped by the acting user's branch — non-global roles never see activity outside their branch.`}
        actions={
          <>
            <span className="inline-flex h-9 items-center gap-1.5 rounded-lg border border-ink-200 bg-white px-3 text-[11px] font-medium text-ink-500">
              <Clock3 className="h-3.5 w-3.5" />
              {directory.summary.latestAt ? `Latest ${formatRelative(directory.summary.latestAt)}` : "No activity yet"}
            </span>
            {can(user, "reports:view") ? (
              <Link
                href="/reports"
                className="inline-flex h-9 items-center gap-1.5 rounded-lg bg-ink-950 px-3.5 text-[12px] font-medium text-white transition hover:bg-ink-900"
              >
                <ScrollText className="h-3.5 w-3.5" /> MIS exports
              </Link>
            ) : null}
          </>
        }
      />

      <section className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4" aria-label="Audit summary">
        <StatCard
          label="Records in scope"
          value={formatNumber(directory.summary.total)}
          hint={scope.isGlobal ? "All branches" : user.branchName}
          icon={<ScrollText className="h-4 w-4" />}
        />
        <StatCard
          label="Distinct actions"
          value={formatNumber(directory.summary.distinctActions)}
          hint="Action codes recorded"
          icon={<Activity className="h-4 w-4" />}
          accent="sky"
        />
        <StatCard
          label="Actors observed"
          value={formatNumber(directory.summary.actors)}
          hint="Unique team members"
          icon={<Users className="h-4 w-4" />}
          accent="amber"
        />
        <StatCard
          label="Matching filters"
          value={formatNumber(directory.items.length)}
          hint="Rows after filters"
          icon={<ShieldCheck className="h-4 w-4" />}
          accent="brand"
        />
      </section>

      <AuditFilters
        actions={directory.actions}
        actors={directory.actors}
        values={{
          q: value("q"),
          action: value("action"),
          actor: value("actor"),
          from: value("from"),
          to: value("to"),
        }}
        activeCount={activeFilterCount}
      />

      <AuditTable items={directory.items} />

      <Card>
        <CardHeader
          title="About this audit trail"
          description="Demo-scoped, append-only activity log"
          action={
            <span className="rounded-md bg-amber-50 px-2 py-1 text-[10px] font-medium text-amber-700 ring-1 ring-inset ring-amber-200">
              DEMO
            </span>
          }
        />
        <div className="grid gap-3 px-5 py-4 text-[10.5px] leading-relaxed text-ink-500 sm:grid-cols-2">
          <p>
            Entries are generated by real actions in this workspace (sign-ins, lead and application changes, status
            updates, exports) and are appended, never rewritten. The store keeps the 500 most recent entries.
          </p>
          <p>
            Branch scope is derived from the acting user at write time. Global roles (Super Admin, Admin) see every
            branch; all other roles see only their own branch. IP addresses are synthetic demo values.
            {directory.summary.latestAt ? ` Most recent entry: ${formatDateTime(directory.summary.latestAt)}.` : ""}
          </p>
        </div>
      </Card>
    </div>
  );
}
